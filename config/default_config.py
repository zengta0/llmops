# =============================================================================
# config/default_config.py —— 配置项的兜底默认值
#
# 作用：当环境变量（.env / 系统环境）里缺少某个 key 时，
#       config.py 里的 _get_env 会回退到这里取值。
#       所以这里写的是「最后一道默认值」，不是实际生效的值。
# =============================================================================

DEFAULT_CONFIG = {
    # -------------------------------------------------------------------------
    # Flask-WTF 的表单校验与 CSRF 防护开关
    # 本项目是纯 JSON API，前端不提交 csrf_token，开启会导致所有表单校验失败，
    # 所以默认关闭。原理详见 config/config.py 里的详细注释。
    # 注意这里写的是字符串 "False" 而不是布尔值 False：
    #   环境变量读出来永远是字符串，_get_bool_env 用 value.lower() == "true" 判定，
    #   写成布尔 False 会导致 .lower() 报错。
    # -------------------------------------------------------------------------
    "WTF_CSRF_ENABLED": "False",

    # -------------------------------------------------------------------------
    # SQLAlchemy 数据库配置
    # -------------------------------------------------------------------------
    # 连接串故意留空：数据库地址与账号密码属于环境相关配置，
    # 必须由 .env 提供，避免代码里硬编码导致误连或泄露。
    "SQLALCHEMY_DATABASE_URI": "",
    # 连接池常驻连接数
    "SQLALCHEMY_POOL_SIZE": 30,
    # 单条连接最长存活秒数（3600 = 1 小时），超时后重建，防止用到已断开的死连接
    "SQLALCHEMY_POOL_RECYCLE": 3600,
    # 是否打印执行的 SQL（开发时开着方便观察 ORM 行为）
    "SQLALCHEMY_ECHO": "True",
}
